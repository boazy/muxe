use std::collections::BTreeMap;
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

use muxe_core::{
    CanonicalKey, ExecutionCapabilities, KeyCapabilities, KeyIdentity, KeyIdentitySource,
    Modifiers, NamedKey, PortableActionKind,
};
use serde::Deserialize;

#[derive(Debug, Deserialize)]
struct ActionCatalog {
    actions: BTreeMap<String, ActionDescription>,
}

#[derive(Debug, Deserialize)]
struct ActionDescription {
    summary: String,
    #[serde(default)]
    parameters: Vec<ParameterDescription>,
}

#[derive(Debug, Deserialize)]
struct ParameterDescription {
    name: String,
    #[serde(rename = "type")]
    type_name: String,
    required: bool,
    #[serde(default)]
    default: Option<String>,
    description: String,
}

struct HostSupport {
    rows: BTreeMap<PortableActionKind, HostSupportRow>,
}

struct HostSupportRow {
    zellij: String,
    herdr: String,
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let mut arguments = env::args_os().skip(1);
    let Some(output) = arguments.next() else {
        return Err(
            "usage: generate_reference <output-path> <host-support.tsv> [action-descriptions.yaml]"
                .into(),
        );
    };
    let Some(host_support_path) = arguments.next() else {
        return Err(
            "usage: generate_reference <output-path> <host-support.tsv> [action-descriptions.yaml]"
                .into(),
        );
    };
    let catalog_path = arguments
        .next()
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from("reference/action-descriptions.yaml"));
    if arguments.next().is_some() {
        return Err(
            "usage: generate_reference <output-path> <host-support.tsv> [action-descriptions.yaml]"
                .into(),
        );
    }

    let host_support = load_host_support(&PathBuf::from(host_support_path))?;
    let catalog = load_action_catalog(&catalog_path)?;
    fs::write(PathBuf::from(output), render(&host_support, &catalog))?;
    Ok(())
}

fn load_action_catalog(path: &PathBuf) -> Result<ActionCatalog, Box<dyn std::error::Error>> {
    let contents = fs::read_to_string(path)?;
    let catalog: ActionCatalog = serde_saphyr::from_str(&contents)?;
    for key in catalog.actions.keys() {
        if PortableActionKind::parse(key).is_none() {
            return Err(format!(
                "{}: unknown action `{key}` in action descriptions catalog",
                path.display()
            )
            .into());
        }
    }
    for action in PortableActionKind::ALL {
        if !catalog.actions.contains_key(action.as_str()) {
            return Err(format!(
                "{}: missing action description for `{}`",
                path.display(),
                action.as_str()
            )
            .into());
        }
    }
    Ok(catalog)
}

#[expect(
    clippy::too_many_lines,
    reason = "the generated reference keeps its ordered document sections together"
)]
fn render(host_support: &HostSupport, catalog: &ActionCatalog) -> String {
    let mut output = String::new();
    writeln!(output, "# Muxe core reference\n").unwrap();
    writeln!(
        output,
        "> Generated by `cargo run --locked -p muxe-core --bin generate_reference -- REFERENCE.md reference/host-support.tsv reference/action-descriptions.yaml`. Do not edit this file by hand.\n"
    )
    .unwrap();
    writeln!(
        output,
        "The key capabilities, action identifiers, and execution defaults are generated from `muxe-core`. The host support mappings are generated from checked-in adapter evidence in `reference/host-support.tsv`. Action explanations and parameter schemas are loaded from `reference/action-descriptions.yaml`."
    )
    .unwrap();

    writeln!(output, "\n## Scope and evidence\n").unwrap();
    writeln!(
        output,
        "Portable actions are host-independent candidates. An active adapter validates a candidate before configuration activation, and an adapter may reject an action that its host cannot represent."
    )
    .unwrap();
    writeln!(
        output,
        "Context references are type-checked while compiling configuration. Muxe resolves them against the attach-time origin and validates the concrete value again before dispatch. A missing context value prevents dispatch.\n"
    )
    .unwrap();
    writeln!(
        output,
        "- **E1 — owned-fixture smoke:** An approved fresh-TempDir Herdr child completed `ping`, observed `Herdr` at its exact configured socket with protocol 20/version 0.8.2, then terminated gracefully and reaped its retained child. It did not smoke a portable action.\n- **E2 — Herdr source evidence:** Adapter mapping and schema tests passed. The mappings below are source-tested, not live action tests.\n- **E3 — Zellij qualified source evidence:** Pinned Rust 1.97.1 source tests passed (55 adapter, 10 protocol, 18 bridge lifecycle) plus the pinned WASM component build. This proves the listed source paths, not a live Zellij host; external artifact digest/grant verification remains blocked."
    )
    .unwrap();

    writeln!(output, "\n## Action schema\n").unwrap();
    writeln!(
        output,
        "Use either a YAML mapping with `type` or a compact action string. In compact form, an unquoted `$origin…` token is a typed context reference; quote it to make it literal. A mapping context reference uses `{{ $context: origin.… }}`.\n"
    )
    .unwrap();
    writeln!(
        output,
        "```yaml\naction:\n  type: command:execute\n  program: cargo\n  cwd:\n    $context: origin.pane.cwd\n\n# Compact form\naction: tab:create workspace-id=$origin.workspace.id\n```"
    )
    .unwrap();

    render_action_inventory(&mut output);
    render_action_catalog(&mut output, host_support, catalog);

    writeln!(output, "\n## Command working directory\n").unwrap();
    writeln!(
        output,
        "The broker never runs `command:execute` in its ambient working directory. It uses the captured origin pane working directory as the execution base."
    )
    .unwrap();
    writeln!(
        output,
        "\n- With no `cwd`, the child uses the captured origin directory.\n- A literal relative `cwd` is joined to the captured origin directory.\n- A context-derived `cwd` must resolve to an absolute path.\n- If the captured origin directory is absent or not absolute, the broker rejects the command before spawning it.\n"
    )
    .unwrap();
    writeln!(
        output,
        "This rule applies to menu command execution. It does not define the omitted `muxe pane open --cwd` behavior."
    )
    .unwrap();

    render_context_references(&mut output);

    writeln!(output, "\n## Canonical key syntax\n").unwrap();
    writeln!(
        output,
        "A canonical key has the form `[selector:]modifier+…+identity`. The selector is omitted for `primary`; `alternate` and `base` select the corresponding terminal identity."
    )
    .unwrap();
    writeln!(
        output,
        "Modifiers must appear once and in this order: `ctrl`, `alt`, `shift`, `super`, `hyper`, `meta`, `caps-lock`, `num-lock`."
    )
    .unwrap();
    writeln!(
        output,
        "Text identities use one printable ASCII character, except `+` and `:`, or `unicode+<hex-scalar>`. Named identities use the generated registry below. Examples: `ctrl+c`, `alternate:alt+unicode+e9`, and `ctrl+f12`.\n"
    )
    .unwrap();

    writeln!(output, "## VT100 aliases\n").unwrap();
    writeln!(
        output,
        "A VT100 terminal reports one legacy event for each of these pairs: `tab` and `ctrl+i`; `enter` and `ctrl+m`; `backspace` and `ctrl+h`; `esc` and `ctrl+[`."
    )
    .unwrap();
    writeln!(
        output,
        "For `ctrl+<letter>`, VT100 also cannot distinguish Shift or ASCII letter case. Muxe rejects a configuration that contains two bindings for one such legacy event. Kitty preserves the identities and modifiers it receives, so these bindings remain distinct there."
    )
    .unwrap();
    writeln!(output, "## Key capability rules\n").unwrap();
    writeln!(
        output,
        "The generated table gives requirements for each named identity with the primary selector and no modifiers."
    )
    .unwrap();
    writeln!(
        output,
        "Applying `alternate:` or `base:` requires alternate-key support. An explicit `repeat:` setting requires event-type support. Lock modifiers require all-keys-as-escape-codes for text identities."
    )
    .unwrap();
    writeln!(
        output,
        "| Named identity | Base capabilities | With explicit `repeat:` |\n|---|---|---|"
    )
    .unwrap();
    for key in NamedKey::FINITE {
        let base = canonical_named(*key).required_capabilities(None);
        let repeated = canonical_named(*key).required_capabilities(Some(true));
        writeln!(
            output,
            "| `{}` | {} | {} |",
            key.as_str(),
            key_capabilities(base),
            key_capabilities(repeated),
        )
        .unwrap();
    }

    writeln!(output, "\n## Native actions\n").unwrap();
    writeln!(
        output,
        "A native action uses a `type` beginning with `native.`. The core retains its source-aware candidate fields, but does not interpret the host schema. The active adapter validates the native type and fields before activation. Example: `native.zellij.command:close-focus`. Native-action availability is therefore adapter evidence, not a claim in this reference."
    )
    .unwrap();

    output
}

fn render_action_inventory(output: &mut String) {
    writeln!(output, "\n### Action inventory\n").unwrap();
    writeln!(output, "| Category | Actions |\n|---|---|").unwrap();
    let categories: &[(&str, &[PortableActionKind])] = &[
        (
            "Menu",
            &[
                PortableActionKind::MenuOpen,
                PortableActionKind::MenuReturn,
                PortableActionKind::MenuQuit,
                PortableActionKind::MenuPagePrev,
                PortableActionKind::MenuPageNext,
            ],
        ),
        ("Configuration", &[PortableActionKind::ConfigReload]),
        ("Keyboard", &[PortableActionKind::KeyboardSend]),
        ("Command", &[PortableActionKind::CommandExecute]),
        (
            "Tab",
            &[
                PortableActionKind::TabCreate,
                PortableActionKind::TabClose,
                PortableActionKind::TabRename,
                PortableActionKind::TabFocus,
                PortableActionKind::TabMove,
                PortableActionKind::TabSwap,
            ],
        ),
        (
            "Pane",
            &[
                PortableActionKind::PaneCreate,
                PortableActionKind::PaneSplit,
                PortableActionKind::PaneClose,
                PortableActionKind::PaneFocus,
                PortableActionKind::PaneMove,
                PortableActionKind::PaneSwap,
                PortableActionKind::PaneResize,
                PortableActionKind::PaneZoom,
                PortableActionKind::PaneFullscreen,
                PortableActionKind::PaneFloating,
                PortableActionKind::PaneFrame,
            ],
        ),
        (
            "Session",
            &[
                PortableActionKind::SessionCreate,
                PortableActionKind::SessionAttach,
                PortableActionKind::SessionSwitch,
                PortableActionKind::SessionRename,
                PortableActionKind::SessionDetach,
                PortableActionKind::SessionQuit,
                PortableActionKind::SessionKill,
            ],
        ),
    ];

    for (name, actions) in categories {
        let links = actions
            .iter()
            .map(|action| {
                let link_anchor = action.as_str().replace([':', '.'], "");
                format!("[`{}`](#{})", action.as_str(), link_anchor)
            })
            .collect::<Vec<_>>()
            .join(", ");
        writeln!(output, "| {name} | {links} |").unwrap();
    }
}

fn render_action_catalog(output: &mut String, host_support: &HostSupport, catalog: &ActionCatalog) {
    writeln!(output, "\n## Portable action catalog\n").unwrap();
    writeln!(
        output,
        "This catalog documents every portable action, its parameter schema, default execution policy, and host-specific adapter behavior."
    )
    .unwrap();

    for action in PortableActionKind::ALL {
        let descriptor = action.descriptor();
        let desc = catalog
            .actions
            .get(action.as_str())
            .expect("action exists in catalog");
        let host_row = host_support
            .rows
            .get(action)
            .expect("action exists in host support");

        writeln!(output, "\n### `{}`\n", action.as_str()).unwrap();
        writeln!(output, "{}\n", desc.summary).unwrap();

        let mode_str = match descriptor.default_execution {
            Some(muxe_core::ExecutionMode::Await) => "`await`",
            Some(muxe_core::ExecutionMode::Detach) => "`detach`",
            None => "synchronous broker execution",
        };
        writeln!(output, "- **Default mode:** {mode_str}").unwrap();
        writeln!(
            output,
            "- **Capabilities:** {}",
            capabilities(descriptor.capabilities)
        )
        .unwrap();
        if let Some(pos) = action.positional_field() {
            writeln!(output, "- **Positional field (compact):** `{pos}`").unwrap();
        }

        writeln!(output, "\n#### Parameters\n").unwrap();
        if desc.parameters.is_empty() {
            writeln!(output, "None.\n").unwrap();
        } else {
            writeln!(
                output,
                "| Parameter | Type | Required | Default | Description |\n|---|---|---|---|---|"
            )
            .unwrap();
            for param in &desc.parameters {
                let default_str = param.default.as_deref().unwrap_or("—");
                let req_str = if param.required { "yes" } else { "no" };
                writeln!(
                    output,
                    "| `{}` | {} | {} | {} | {} |",
                    param.name, param.type_name, req_str, default_str, param.description
                )
                .unwrap();
            }
            writeln!(output).unwrap();
        }

        let alert_kind = if action.as_str() == "session:kill" {
            "CAUTION"
        } else if host_row.zellij.contains("Rejected")
            || host_row.zellij.contains("Incompatible")
            || host_row.herdr.contains("Incompatible")
        {
            "WARNING"
        } else {
            "NOTE"
        };

        writeln!(output, "\n> [!{alert_kind}]").unwrap();
        writeln!(output, "> **Zellij:** {}\n>", host_row.zellij).unwrap();
        writeln!(output, "> **Herdr:** {}", host_row.herdr).unwrap();
    }
}


use std::collections::BTreeMap;
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

use muxe_core::{
    CanonicalKey, ExecutionCapabilities, KeyCapabilities, KeyIdentity, KeyIdentitySource,
    Modifiers, NamedKey, PortableActionKind,
};
struct HostSupport {
    rows: BTreeMap<PortableActionKind, HostSupportRow>,
}

struct HostSupportRow {
    zellij: String,
    herdr: String,
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let mut arguments = env::args_os().skip(1);
    let Some(output) = arguments.next() else {
        return Err("usage: generate_reference <output-path> <host-support.tsv>".into());
    };
    let Some(host_support) = arguments.next() else {
        return Err("usage: generate_reference <output-path> <host-support.tsv>".into());
    };
    if arguments.next().is_some() {
        return Err("usage: generate_reference <output-path> <host-support.tsv>".into());
    }

    let host_support = load_host_support(&PathBuf::from(host_support))?;
    fs::write(PathBuf::from(output), render(&host_support))?;
    Ok(())
}

fn render(host_support: &HostSupport) -> String {
    let mut output = String::new();
    writeln!(output, "# Muxe core reference\n").unwrap();
    writeln!(
        output,
        "> Generated by `cargo run --locked -p muxe-core --bin generate_reference -- REFERENCE.md reference/host-support.tsv`. Do not edit this file by hand.\n"
    )
    .unwrap();
    writeln!(
        output,
        "The key and portable-action tables are generated from `muxe-core`. The host table is generated from checked-in adapter evidence. Every host claim carries its evidence status."
    )
    .unwrap();

    writeln!(output, "\n## Scope and evidence\n").unwrap();
    writeln!(
        output,
        "Portable actions are host-independent candidates. An active adapter validates a candidate before configuration activation, and an adapter may reject an action that its host cannot represent."
    )
    .unwrap();
    writeln!(
        output,
        "Context references are type-checked while compiling configuration. Muxe resolves them against the attach-time origin and validates the concrete value again before dispatch. A missing context value prevents dispatch."
    )
    .unwrap();

    writeln!(output, "\n## Action schema\n").unwrap();
    writeln!(
        output,
        "Use either a YAML mapping with `type` or a compact action string. In compact form, an unquoted `$origin…` token is a typed context reference; quote it to make it literal. A mapping context reference uses `{{ $context: origin.… }}`.\n"
    )
    .unwrap();
    writeln!(output, "```yaml\naction:\n  type: command:execute\n  program: cargo\n  cwd:\n    $context: origin.pane.cwd\n\n# Compact form\naction: tab:create workspace-id=$origin.workspace.id\n```\n").unwrap();
    writeln!(output, "| Portable action | Accepted fields | Default mode | Capabilities | Evidence |\n|---|---|---|---|---|").unwrap();
    for action in PortableActionKind::ALL {
        let descriptor = action.descriptor();
        writeln!(
            output,
            "| `{}` | {} | {} | {} | Core source only |",
            action.as_str(),
            descriptor.parameter_syntax,
            descriptor
                .default_execution
                .map(|mode| match mode {
                    muxe_core::ExecutionMode::Await => "await",
                    muxe_core::ExecutionMode::Detach => "detach",
                })
                .unwrap_or("—"),
            capabilities(descriptor.capabilities),
        )
        .unwrap();
    }

    writeln!(output, "\n## Command working directory\n").unwrap();
    writeln!(
        output,
        "The broker never runs `command:execute` in its ambient working directory. It uses the captured origin pane working directory as the execution base."
    )
    .unwrap();
    writeln!(
        output,
        "\n- With no `cwd`, the child uses the captured origin directory.\n- A literal relative `cwd` is joined to the captured origin directory.\n- A context-derived `cwd` must resolve to an absolute path.\n- If the captured origin directory is absent or not absolute, the broker rejects the command before spawning it.\n"
    )
    .unwrap();
    writeln!(
        output,
        "This rule applies to menu command execution. It does not define the omitted `muxe pane open --cwd` behavior."
    )
    .unwrap();

    render_host_support(&mut output, host_support);

    writeln!(output, "\n## Canonical key syntax\n").unwrap();
    writeln!(
        output,
        "A canonical key has the form `[selector:]modifier+…+identity`. The selector is omitted for `primary`; `alternate` and `base` select the corresponding terminal identity."
    )
    .unwrap();
    writeln!(
        output,
        "Modifiers must appear once and in this order: `ctrl`, `alt`, `shift`, `super`, `hyper`, `meta`, `caps-lock`, `num-lock`."
    )
    .unwrap();
    writeln!(
        output,
        "Text identities use one printable ASCII character, except `+` and `:`, or `unicode+<hex-scalar>`. Named identities use the generated registry below. Examples: `ctrl+c`, `alternate:alt+unicode+e9`, and `ctrl+f12`.\n"
    )
    .unwrap();

    writeln!(output, "## VT100 aliases\n").unwrap();
    writeln!(
        output,
        "A VT100 terminal reports one legacy event for each of these pairs: `tab` and `ctrl+i`; `enter` and `ctrl+m`; `backspace` and `ctrl+h`; `esc` and `ctrl+[`."
    )
    .unwrap();
    writeln!(
        output,
        "For `ctrl+<letter>`, VT100 also cannot distinguish Shift or ASCII letter case. Muxe rejects a configuration that contains two bindings for one such legacy event. Kitty preserves the identities and modifiers it receives, so these bindings remain distinct there."
    )
    .unwrap();
    writeln!(output, "## Key capability rules\n").unwrap();
    writeln!(
        output,
        "The generated table gives requirements for each named identity with the primary selector and no modifiers."
    )
    .unwrap();
    writeln!(
        output,
        "Applying `alternate:` or `base:` requires alternate-key support. An explicit `repeat:` setting requires event-type support. Lock modifiers require all-keys-as-escape-codes for text identities."
    )
    .unwrap();
    writeln!(
        output,
        "| Named identity | Base capabilities | With explicit `repeat:` |\n|---|---|---|"
    )
    .unwrap();
    for key in NamedKey::FINITE {
        let base = canonical_named(*key).required_capabilities(None);
        let repeated = canonical_named(*key).required_capabilities(Some(true));
        writeln!(
            output,
            "| `{}` | {} | {} |",
            key.as_str(),
            key_capabilities(base),
            key_capabilities(repeated),
        )
        .unwrap();
    }

    writeln!(output, "\n## Native actions\n").unwrap();
    writeln!(
        output,
        "A native action uses a `type` beginning with `native.`. The core retains its source-aware candidate fields, but does not interpret the host schema. The active adapter validates the native type and fields before activation. Native-action availability is therefore adapter evidence, not a claim in this reference."
    )
    .unwrap();

    output
}

fn load_host_support(path: &PathBuf) -> Result<HostSupport, Box<dyn std::error::Error>> {
    let contents = fs::read_to_string(path)?;
    let mut rows = BTreeMap::new();
    for (line_number, line) in contents.lines().enumerate() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let columns = line.split('\t').collect::<Vec<_>>();
        if columns.len() != 3 {
            return Err(format!(
                "{}:{}: expected action, Zellij mapping, and Herdr mapping separated by tabs",
                path.display(),
                line_number + 1,
            )
            .into());
        }
        let action = columns[0].trim();
        let kind = PortableActionKind::parse(action).ok_or_else(|| {
            format!("{}:{}: unknown portable action `{action}`", path.display(), line_number + 1)
        })?;
        let row = HostSupportRow {
            zellij: columns[1].trim().to_owned(),
            herdr: columns[2].trim().to_owned(),
        };
        if rows.insert(kind, row).is_some() {
            return Err(format!(
                "{}:{}: duplicate portable action `{action}`",
                path.display(),
                line_number + 1,
            )
            .into());
        }
    }
    for action in PortableActionKind::ALL {
        if !rows.contains_key(action) {
            return Err(format!(
                "{}: missing host support for `{}`",
                path.display(),
                action.as_str()
            )
            .into());
        }
    }
    Ok(HostSupport { rows })
}

fn render_host_support(output: &mut String, host_support: &HostSupport) {
    writeln!(output, "\n## Host support evidence\n").unwrap();
    writeln!(
        output,
        "- **E1 — owned-fixture smoke:** An approved fresh-TempDir Herdr child completed `ping`, observed `Herdr` at its exact configured socket with protocol 20/version 0.8.2, then terminated gracefully and reaped its retained child. It did not smoke a portable action.\n- **E2 — Herdr source evidence:** Adapter mapping and schema tests passed. The mappings below are source-tested, not live action tests.\n- **E3 — Zellij source evidence:** Pinned 0.46.0 conversion and inventory checks passed. No active Zellij host smoke has run.\n"
    )
    .unwrap();
    writeln!(
        output,
        "| Portable action | Zellij mapping and constraints (E3) | Herdr mapping and constraints (E1/E2) |\n|---|---|---|"
    )
    .unwrap();
    for action in PortableActionKind::ALL {
        let row = host_support.rows.get(action).expect("host support was validated");
        writeln!(
            output,
            "| `{}` | {} | {} |",
            action.as_str(),
            row.zellij,
            row.herdr,
        )
        .unwrap();
    }
}

fn canonical_named(named: NamedKey) -> CanonicalKey {
    CanonicalKey {
        source: KeyIdentitySource::Primary,
        modifiers: Modifiers::empty(),
        identity: KeyIdentity::Named(named),
    }
}

fn capabilities(capabilities: ExecutionCapabilities) -> &'static str {
    match (
        capabilities.awaitable,
        capabilities.detachable,
        capabilities.cancellable,
    ) {
        (false, false, false) => "none",
        (true, false, false) => "awaitable",
        (true, true, false) => "awaitable, detachable",
        (true, true, true) => "awaitable, detachable, cancellable",
        (true, false, true) => "awaitable, cancellable",
        (false, true, false) => "detachable",
        (false, true, true) => "detachable, cancellable",
        (false, false, true) => "cancellable",
    }
}

fn key_capabilities(capabilities: KeyCapabilities) -> &'static str {
    match (
        capabilities.event_types,
        capabilities.alternate_keys,
        capabilities.all_keys_as_escape_codes,
    ) {
        (false, false, false) => "none",
        (true, false, false) => "event types",
        (false, true, false) => "alternate keys",
        (false, false, true) => "all keys as escape codes",
        (true, true, false) => "event types, alternate keys",
        (true, false, true) => "event types, all keys as escape codes",
        (false, true, true) => "alternate keys, all keys as escape codes",
        (true, true, true) => "event types, alternate keys, all keys as escape codes",
    }
}
